/** The published-id allowlist, validated: an array of safe id strings, non-empty. `source` is for tests only. */
function publishedIds(source) {
  const src = arguments.length ? source : PUBLISHED;
  const ids = src && Array.isArray(src.ids) ? src.ids : [];
  const ok = ids.length > 0 && ids.every((x) => typeof x === 'string' && /^[A-Za-z0-9_-]+$/.test(x));
  return new Set(ok ? ids : []);                       // a broken / empty file publishes NOTHING (fail closed)
}

/** The SAME mapping quote-builder-v2.html's loadDatabase() applies to a `products` doc (cost fields deliberately absent). */
function normaliseProductDoc(id, data) {
  const p = data || {};
  return {
    id,
    category: p.category,
    name: p.title || p.name || '',
    formulaType: p.formulaType || 'fixed',
    basePrice: p.basePrice ?? p.baseRate ?? 0,
    defaultDimensions: p.measurement || p.defaultDimensions || {},
    formula: p.formula || {},
    specs: Array.isArray(p.specs) ? p.specs : [],
    unit: p.unit || 'pc',
  };
}

/** [{id, data}] (Firestore docs) -> Map id -> normalised product, PUBLISHED products only. */
function buildProductIndex(docs, published) {
  const allow = published || publishedIds();
  const byId = new Map();
  (docs || []).forEach((d) => {
    if (!d || typeof d.id !== 'string' || !allow.has(d.id)) return;
    byId.set(d.id, normaliseProductDoc(d.id, d.data));
  });
  return byId;
}

/** The primary SKU id of every family — these products are LOADED (the price of a configured line starts from one) but are not quotable on their own. */
function familyPrimaryIds(families) {
  const f = families || FAMILIES;
  return new Set((f.order || []).map((id) => f.families[id].primary));
}

/**
 * [{id, data}] -> { byId, primaries }. `byId` = the QUOTABLE fixed SKUs (qr-published.json), `primaries` = Map familyId -> the normalised
 * primary SKU of each family (loaded even though it is absorbed). Any other product doc is dropped.
 */
function buildCatalogueIndex(docs, opts) {
  const o = opts || {};
  const quotable = o.quotable || publishedIds();
  const families = o.families || FAMILIES;
  const primaryIds = familyPrimaryIds(families);
  const all = buildProductIndex(docs, new Set([...quotable, ...primaryIds]));
  const byId = new Map();
  all.forEach((p, id) => { if (quotable.has(id)) byId.set(id, p); });
  const primaries = new Map();
  (families.order || []).forEach((fid) => { const p = all.get(families.families[fid].primary); if (p) primaries.set(fid, p); });
  return { byId, primaries };
}

/** [{id, data}] (product_pricing docs) -> Map familyId -> the SANITISED sheet (see pricing-core.normalisePricingDoc). Unknown family ids are dropped. */
function buildPricingIndex(docs, families) {
  const f = families || FAMILIES;
  const out = new Map();
  (docs || []).forEach((d) => {
    if (!d || typeof d.id !== 'string' || !has(f.families, d.id)) return;
    out.set(d.id, pricing.normalisePricingDoc(f.families[d.id], d.data));
  });
  return out;
}

/** productMeta/config.constants (the multiplier) — a plain object, never null. */
function constantsOf(meta) { return isPlainObject(meta) && isPlainObject(meta.constants) ? meta.constants : {}; }
/** O7 kill-switch: the estimate is on unless productMeta/config.quoteRequest.estimateEnabled === false. */
function estimateEnabledOf(meta) {
  return !(isPlainObject(meta) && isPlainObject(meta.quoteRequest) && meta.quoteRequest.estimateEnabled === false);
}
/**
 * Per-family kill-switch (CONFIGURATOR-FAMILIES-2-SPEC §9): productMeta/config.families.disabled is a list of family ids the owner has switched OFF
 * on the website without a deploy. -> an array of the distinct, non-empty STRING entries (exact ids — no trimming, no case folding — because the
 * website and the Quote Builder must read the one list the same way); anything else — no list, a list that is not an array, a number or an object
 * among the entries — contributes nothing, so a malformed document can only ever leave a family ON (the same fail-open reading as estimateEnabledOf).
 */
function disabledFamiliesOf(meta) {
  const list = isPlainObject(meta) && isPlainObject(meta.families) ? meta.families.disabled : null;
  const out = [];
  if (Array.isArray(list)) list.forEach((id) => { if (typeof id === 'string' && id !== '' && !out.includes(id)) out.push(id); });
  return out;
}

/** 'fresh' (< 10 min) | 'stale' (< 24 h: may cover a failed refresh) | 'dead' (older) | 'empty'. */
function productsCacheState(cache, nowMs) {
  if (!cache || !Number.isFinite(cache.loadedAt)) return 'empty';
  const age = nowMs - cache.loadedAt;
  if (age < 0) return 'stale';
  if (age < PRODUCTS_TTL_MS) return 'fresh';
  if (age < PRODUCTS_MAX_STALE_MS) return 'stale';
  return 'dead';
}

