/** A tiny insertion-ordered LRU with a TTL — the per-instance estimate cache. Cache hits still count against the rate buckets. */
function createLru(max, ttlMs) {
  const map = new Map();
  return {
    get(key, nowMs) {
      const hit = map.get(key);
      if (!hit) return undefined;
      if (nowMs - hit.at > ttlMs) { map.delete(key); return undefined; }
      map.delete(key); map.set(key, hit);               // refresh recency
      return hit.value;
    },
    set(key, value, nowMs) {
      if (map.has(key)) map.delete(key);
      map.set(key, { value, at: nowMs });
      while (map.size > max) map.delete(map.keys().next().value);
    },
    get size() { return map.size; },
  };
}

