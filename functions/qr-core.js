const INTAKE_KEYS = ['need', 'needOther', 'useFor', 'useForOther', 'entityType', 'targetDate', 'targetFlexible', 'address', 'notes'];
const CONTACT_KEYS = ['name', 'mobile', 'email', 'company'];
const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

function optionValues(field) { return INTAKE[field].options.map((o) => o.v); }
function optionLabel(field, v) {
  const hit = INTAKE[field].options.filter((o) => o.v === v)[0];
  return hit ? hit.l : '';
}

/** A calendar-valid 'YYYY-MM-DD'? (year 2000..2100, month/day real). */
function isCalendarDate(s) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(s));
  if (!m) return false;
  const yr = Number(m[1]), mo = Number(m[2]), da = Number(m[3]);
  if (yr < 2000 || yr > 2100) return false;
  const d = new Date(Date.UTC(yr, mo - 1, da));
  return d.getUTCFullYear() === yr && d.getUTCMonth() === mo - 1 && d.getUTCDate() === da;
}
/** 'YYYY-MM-DD' plus n years (a Feb 29 rolls to Mar 1 — only used for an upper bound). */
function addYears(iso, n) {
  const d = new Date(Date.UTC(Number(iso.slice(0, 4)) + n, Number(iso.slice(5, 7)) - 1, Number(iso.slice(8, 10))));
  return d.toISOString().slice(0, 10);
}

/** raw intake -> { ok, errors, clean }. `nowMs` anchors the target-date window to the MANILA date. */
function validateIntake(raw, nowMs) {
  const errors = [];
  const clean = {};
  const r = isPlainObject(raw) ? raw : {};
  Object.keys(r).forEach((k) => { if (!INTAKE_KEYS.includes(k)) errors.push(`Unknown field "${k}"`); });

  // the three selects, each with an optional "other" text
  [['need', 'needOther'], ['useFor', 'useForOther']].forEach(([key, otherKey]) => {
    const v = r[key];
    if (typeof v !== 'string' || !optionValues(key).includes(v)) { errors.push(`"${INTAKE[key].label}" is required.`); return; }
    clean[key] = v;
    const other = has(r, otherKey) && r[otherKey] != null ? r[otherKey] : '';
    if (v === 'other') {
      const t = typeof other === 'string' ? stripText(other) : '';
      if (!t) errors.push(`Please say what "${INTAKE[key].label}" means for you.`);
      else if (t.length > 120) errors.push(`"${INTAKE[key].label}" — your description is too long.`);
      else clean[otherKey] = t;
    } else if (other !== '') {
      errors.push(`"${otherKey}" is only allowed when "Other" is chosen.`);
    }
  });
  if (typeof r.entityType !== 'string' || !optionValues('entityType').includes(r.entityType)) errors.push(`"${INTAKE.entityType.label}" is required.`);
  else clean.entityType = r.entityType;

  // target date: a real date from today (Manila) to three years out, OR "not sure yet" with no date
  const flexible = r.targetFlexible === true;
  if (has(r, 'targetFlexible') && r.targetFlexible !== true && r.targetFlexible !== false && r.targetFlexible != null) errors.push('"Not sure yet" must be a yes/no value.');
  const td = r.targetDate;
  if (flexible) {
    if (td != null && td !== '') errors.push('Choose a target date or "Not sure yet", not both.');
    else { clean.targetDate = null; clean.targetFlexible = true; }
  } else if (td == null || td === '') {
    errors.push(`"${INTAKE.targetDate.label}" is required (or tick "${INTAKE.targetDate.flexibleLabel}").`);
  } else if (typeof td !== 'string' || !isCalendarDate(td)) {
    errors.push(`"${INTAKE.targetDate.label}" is not a valid date.`);
  } else {
    const today = portal.manilaDateFrom(nowMs);
    if (td < today) errors.push(`"${INTAKE.targetDate.label}" cannot be in the past.`);
    else if (td > addYears(today, 3)) errors.push(`"${INTAKE.targetDate.label}" is too far ahead — please pick a date within three years.`);
    else { clean.targetDate = td; clean.targetFlexible = false; }
  }

  // address (multiline) and notes (optional, multiline)
  const addr = typeof r.address === 'string' ? stripText(r.address, { multiline: true }) : '';
  if (addr.length < 5) errors.push(`"${INTAKE.address.label}" is required.`);
  else if (addr.length > INTAKE.address.max) errors.push(`"${INTAKE.address.label}" is too long.`);
  else clean.address = addr;
  if (has(r, 'notes') && r.notes != null && r.notes !== '') {
    const n = typeof r.notes === 'string' ? stripText(r.notes, { multiline: true }) : null;
    if (n === null) errors.push('Notes must be text.');
    else if (n.length > INTAKE.notes.max) errors.push('Notes are too long.');
    else if (n) clean.notes = n;
  }
  return { ok: errors.length === 0, errors, clean };
}

/** Philippine mobile -> '09XXXXXXXXX', or null. Accepts 09…, +639…, 639… with spaces, dashes, dots, brackets. */
function normaliseMobile(s) {
  if (typeof s !== 'string') return null;
  const t = s.replace(/[\s\-.()]/g, '');
  if (/^09\d{9}$/.test(t)) return t;
  const m = /^(?:\+?63)(9\d{9})$/.exec(t);
  return m ? '0' + m[1] : null;
}

/** raw contact -> { ok, errors, clean:{ name, mobile, email, company } } */
function validateContact(raw) {
  const errors = [];
  const clean = {};
  const r = isPlainObject(raw) ? raw : {};
  Object.keys(r).forEach((k) => { if (!CONTACT_KEYS.includes(k)) errors.push(`Unknown field "${k}"`); });
  const name = typeof r.name === 'string' ? stripText(r.name) : '';
  if (name.length < 2) errors.push(`"${INTAKE.name.label}" is required.`);
  else if (name.length > INTAKE.name.max) errors.push(`"${INTAKE.name.label}" is too long.`);
  else clean.name = name;
  const mobile = normaliseMobile(r.mobile);
  if (!mobile) errors.push('Enter a Philippine mobile number (09XX XXX XXXX).');
  else clean.mobile = mobile;
  const email = typeof r.email === 'string' ? stripText(r.email) : '';
  if (!email) errors.push(`"${INTAKE.email.label}" is required.`);
  else if (email.length > INTAKE.email.max || !EMAIL_RE.test(email)) errors.push('Enter a valid e-mail address.');
  else clean.email = email;
  const company = r.company == null ? '' : (typeof r.company === 'string' ? stripText(r.company) : null);
  if (company === null) errors.push('Company must be text.');
  else if (company.length > INTAKE.company.max) errors.push('Company is too long.');
  else clean.company = company;
  return { ok: errors.length === 0, errors, clean };
}

