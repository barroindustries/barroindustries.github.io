/**
 * True only for a JSON-shaped tree of plain data: every object's prototype is exactly Object.prototype, every array is a
 * real Array, no accessor/symbol keys, within a depth and node budget. WHY: firebase-functions' request decoder re-assigns
 * each key with bracket assignment, so a wire body {"__proto__":{...}} makes the handler receive an object with NO own keys
 * whose fields all live on its prototype — invisible to JSON.stringify(data).length (the payload-size guard) and to every
 * Object.keys() allowlist (unknown / family / config keys). Rejecting any non-plain prototype closes both holes at once.
 * Pure; never throws.
 */
function isPlainJsonTree(value, maxDepth, maxNodes) {
  const depthMax = Number.isInteger(maxDepth) ? maxDepth : 8;
  const nodeMax = Number.isInteger(maxNodes) ? maxNodes : 4000;
  let nodes = 0;
  function walk(x, depth) {
    if (++nodes > nodeMax || depth > depthMax) return false;
    if (x === null || x === undefined) return true;
    const t = typeof x;
    if (t === 'string' || t === 'boolean' || t === 'number') return true;
    if (t !== 'object') return false;                                   // function, symbol, bigint
    try {
      if (Array.isArray(x)) {
        if (Object.getPrototypeOf(x) !== Array.prototype) return false;
        for (let i = 0; i < x.length; i++) { if (!(i in x)) return false; if (!walk(x[i], depth + 1)) return false; }
        return true;
      }
      if (Object.getPrototypeOf(x) !== Object.prototype) return false;
      if (Object.getOwnPropertySymbols(x).length) return false;
      const names = Object.getOwnPropertyNames(x);
      for (const k of names) {
        const d = Object.getOwnPropertyDescriptor(x, k);
        if (!d || !('value' in d)) return false;                        // accessor
        if (!walk(d.value, depth + 1)) return false;
      }
      return true;
    } catch (_) { return false; }
  }
  return walk(value, 0);
}

