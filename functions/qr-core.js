/** A session (as read from qr_sessions) is usable: exists, not submitted, created within the TTL. */
function sessionUsable(session, createdMs, nowMs) {
  if (!session || session.submittedAt != null) return false;
  return Number.isFinite(createdMs) && createdMs > 0 && (nowMs - createdMs) <= LIMITS.sessionTtlMs;
}

/**
 * The per-session estimate counter (§5.1) — 150 per 24 h independent of IP rotation. Pure verdict: never throws.
 * -> { allowed, next } where `next` is the field set to write when allowed (count +1, or a fresh window of 1 once the
 * last estimate is more than 24 h old).
 */
function sessionEstimateDecision(session, nowMs, basketHashStr) {
  const s = session || {};
  const count = Number.isInteger(s.estimateCount) ? s.estimateCount : 0;
  const lastMs = Number.isFinite(s.lastEstimateMs) ? s.lastEstimateMs : null;
  const windowLive = lastMs != null && (nowMs - lastMs) < RATE.estimateSession.window;
  if (count >= RATE.estimateSession.max && windowLive) return { allowed: false, next: null };
  const nextCount = (count >= RATE.estimateSession.max && !windowLive) ? 1 : count + 1;
  return { allowed: true, next: { estimateCount: nextCount, lastBasketHash: basketHashStr || null } };
}

/** honeypot non-empty, or submitted sooner than minFillMs after the session was created. */
function botCheck(opts) {
  const o = opts || {};
  const hp = String(o.honeypot == null ? '' : o.honeypot).trim();
  if (hp) return { bot: true, reason: 'honeypot' };
  const created = Number(o.sessionCreatedMs);
  const now = Number(o.nowMs);
  if (!Number.isFinite(created) || !Number.isFinite(now) || (now - created) < LIMITS.minFillMs) return { bot: true, reason: 'too_fast' };
  return { bot: false, reason: null };
}

