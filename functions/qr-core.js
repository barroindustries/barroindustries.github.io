/** Plain emoji only (never emojiIcon()); every attacker-supplied string loses '<' and control characters (the OS push banner renders raw text). */
function notifSafe(s) { return String(s == null ? '' : s).replace(/[<\x00-\x1F\x7F]/g, '').trim(); }

/** The in-app + push notification for a new request. NEVER carries the internal exact figure — lock screens show push bodies. */
function buildNotification(doc) {
  const d = doc || {};
  const s = d.summary || {};
  const ref = notifSafe(d.refNo);
  const who = notifSafe(s.company) || notifSafe(s.name) || 'unnamed requester';
  let title = `🧾 New quote request — ${who}`;
  if (title.length > 200) title = title.slice(0, 200);
  const n = Number.isFinite(s.itemCount) ? s.itemCount : 0;
  const peso = (x) => Number(x).toLocaleString('en-PH');
  let body = `${notifSafe(s.name) || 'A visitor'} · ${notifSafe(optionLabel('need', s.need)) || 'need not given'} · ${notifSafe(optionLabel('useFor', s.useFor)) || 'use not given'} · ${n} item${n === 1 ? '' : 's'}`
    + (s.estimateShown ? ` · est. ₱${peso(s.estimateLow)}–₱${peso(s.estimateHigh)}` : '')
    + ` · Ref ${ref}. Open Sales → Quote requests.`;
  if (body.length > 2000) body = body.slice(0, 2000);
  return { title, body, icon: '🧾', type: 'quote_request', link: 'dept:Sales' };
}

