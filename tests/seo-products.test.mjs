  const SKIP_DIRS = new Set(['.git', '.github', '.githooks', '.claude', '.vscode', 'node_modules', 'functions', 'private', 'archive', 'downloads', 'site', 'icons', 'js', 'css', 'data', 'docs', 'specs', 'tests', 'scripts', 'fable-workplan']);
