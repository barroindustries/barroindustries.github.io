#!/usr/bin/env node
/**
 * build-guides-hub.js — writes the front page of The Kitchen Guide (guides/index.html) from scripts/guides-hub.json, the photo manifests
 * (scripts/guide-photos-*.json) and the articles themselves (guides/<slug>/index.html: H1, dates, reading time).
 *
 *   node scripts/build-guides-hub.js            rewrite the generated part of guides/index.html
 *   node scripts/build-guides-hub.js --check    exit 1 and say what is stale (CHECK 9 of scripts/ci-invariants.sh runs this)
 *
 * WHAT IT WRITES. Everything between the two marker comments directly inside <main> — the masthead, the topic bar, the lead story and four
 * features, "Start here", "Latest", the topic sections (with a native <details> for the overflow), the colophon — and, inside the page's JSON-LD,
 * the CollectionPage's ItemList (every published article, in registry order, with numberOfItems) and its dateModified. The head copy (title,
 * description, Open Graph) and the closing "Tell us about your project" section are hand-written and stay as they are.
 *
 * RUN ORDER after any change to a guide or to scripts/guides-hub.json:
 *   node scripts/apply-guide-template.js && node scripts/build-guides-hub.js && node scripts/inline-page-css.js && node scripts/sitemap-lastmod.js
 *
 * FAILS LOUDLY when: a config slug has no page; a page on disk is in no articles[] entry (except editorial-standards); the pillar page is missing; lead,
 * features and startHere repeat or name an unknown slug; a section has no rendered topic to land on; a photograph file (or its -320 variant) is missing.
 * The spec is specs/KITCHEN-GUIDE-JOURNAL-SPEC.md (§3 the page, §8 this script).
 */
'use strict';

const fs = require('fs');
const path = require('path');
const L = require('./guides-lib.js');

const { ROOT, BASE, esc, monthYear } = L;
const HUB = path.join(ROOT, 'guides/index.html');
const START = '<!-- KG-HUB:START — generated by scripts/build-guides-hub.js — DO NOT HAND-EDIT: edit scripts/guides-hub.json, then run node scripts/build-guides-hub.js -->';
const END = '<!-- KG-HUB:END -->';
const TOP = 3;             // photo cards at the head of a topic
const ROWS = 6;            // then this many rows, then a <details> for the rest
const LATEST = 6;

class HubError extends L.GuidesError {}
const fail = (m) => { throw new HubError(m); };

// ── load and check everything ─────────────────────────────────────────────────────────────────────────────────────────────────────────
function load() {
  const ctx = L.loadRegistry();
  const { cfg, bySlug } = ctx;
  // the teasers
  const picks = [cfg.lead, ...cfg.features, ...cfg.startHere];
  for (const s of [cfg.lead, ...cfg.features, ...cfg.startHere, cfg.pillar]) if (!bySlug[s]) fail(`"${s}" (lead, a feature, a Start-here step or the pillar) is not a published article`);
  if (new Set(picks).size !== picks.length) fail('lead, features and startHere repeat a slug');
  if (cfg.features.length !== 4) fail('exactly four features are needed');
  if (cfg.startHere.length !== 5) fail('exactly five Start-here steps are needed');
  if (cfg.startHere.includes(cfg.pillar) || cfg.features.includes(cfg.pillar)) fail('the pillar is the lead or the head of Start here, not a feature or a step');
  if (!L.exists(L.articleFile(cfg.pillar))) fail(`the pillar page guides/${cfg.pillar}/index.html is missing; the hub does not ship without it`);
  return ctx;
}

// ── photographs ───────────────────────────────────────────────────────────────────────────────────────────────────────────────────────
// the manifest entry of an article; with none, the article's own hero picture is the one file every slot uses
function photo(ctx, a) {
  const p = L.photoOf(a.slug, ctx.manifest);
  if (p) { L.checkPhotoFiles(p); return p; }
  const h = a.hero;
  if (!h.src) fail(`${a.slug}: no manifest entry and no hero picture`);
  const small = h.srcset ? h.srcset.split(',').map((s) => s.trim().split(/\s+/)).sort((x, y) => parseInt(x[1], 10) - parseInt(y[1], 10))[0][0] : h.src;
  return { slug: a.slug, single: true, alt: h.alt, s1600: h.src, s1000: small, s600: small, s320: small };
}
function img(p, o) {
  if (p.single) { const d = L.dims(o.src); return `<img src="${o.src}" width="${d.w}" height="${d.h}" alt="${esc(p.alt)}"${o.eager ? ' fetchpriority="high" decoding="async"' : ' loading="lazy" decoding="async"'}>`; }
  return L.imgTag({ ...o, alt: p.alt });
}
const SIZES = {
  lead: '(min-width:1024px) 680px, (min-width:720px) 90vw, 70vw',
  pillar: '(min-width:1024px) 480px, (min-width:720px) 90vw, 70vw',
  card: '(min-width:1024px) 370px, (min-width:720px) 31vw, 92vw',
  cardRow: '(min-width:1024px) 370px, (min-width:720px) 31vw, 96px',
  feature: '(min-width:1024px) 150px, 112px',
  row: '96px',
};
const imgLead = (p) => img(p, { src: p.s1000, srcset: [[p.s600, 600], [p.s1000, 1000], [p.s1600, 1600]], sizes: SIZES.lead, eager: true });
const imgPillar = (p) => img(p, { src: p.s600, srcset: [[p.s320, 320], [p.s600, 600], [p.s1000, 1000]], sizes: SIZES.pillar });
const imgCard = (p) => img(p, { src: p.s600, srcset: [[p.s320, 320], [p.s600, 600]], sizes: SIZES.card });
const imgCardRow = (p) => img(p, { src: p.s320, srcset: [[p.s320, 320], [p.s600, 600]], sizes: SIZES.cardRow });
const imgFeature = (p) => img(p, { src: p.s320, srcset: [[p.s320, 320], [p.s600, 600]], sizes: SIZES.feature });
const imgRow = (p) => img(p, { src: p.s320, srcset: [[p.s320, 320], [p.s600, 600]], sizes: SIZES.row });

// ── markup ────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────
// every visible date of the page is the month and the year (owner ruling 2026-11-23: L.monthYear); the exact date stays in each <time datetime="…">. The dateline spells the month out
// ("November 2026"); a card abbreviates it ("Nov 2026") so that "<date> · 6 min read" stays on one line in the narrow rows of a phone
const meta = (a) => `<p class="kg-meta"><time datetime="${a.published}">${monthYear(a.published, { short: true })}</time><span aria-hidden="true">·</span><span>${a.mins} min read</span></p>`;
const href = (a) => `/guides/${a.slug}/`;
const head = (a) => `<h3><a href="${href(a)}">${esc(a.h1)}</a></h3>`;
const media = (html) => `<div class="pg-card-media">${html}</div>`;

function render(ctx) {
  const { cfg, bySlug, sections, secById, arts } = ctx;
  const P = (a) => photo(ctx, a);
  const secTitle = (a) => secById[a.section].title;
  const lead = bySlug[cfg.lead], pillar = bySlug[cfg.pillar];
  const pillarIsLead = cfg.lead === cfg.pillar;
  const newest = arts.reduce((m, a) => [a.published, a.modified].reduce((x, y) => (y > x ? y : x), m), '0000-00-00');
  const nTopics = sections.length;
  const out = [];

  // 1 · masthead
  out.push(`<section class="pg-hero pg-hero-plain kg-mast">
  <div class="site-wrap pg-hero-in">
    <div class="pg-hero-copy">
      <nav class="crumbs" aria-label="Breadcrumb"><ol><li><a href="/">Home</a></li><li><span aria-current="page">The Kitchen Guide</span></li></ol></nav>
      <p class="kg-dateline"><span>Quezon City, Philippines</span><span>Updated <time datetime="${newest}">${monthYear(newest)}</time></span></p>
      <h1>The Kitchen Guide</h1>
      <p class="kg-by">by Barro Kitchens</p>
      <p class="kg-tagline">${esc(cfg.tagline)}</p>
      <p class="kg-count">${arts.length} articles · ${nTopics} topics · <a href="${L.STANDARDS_PATH}">How we research and cite</a></p>
    </div>
  </div>
</section>`);

  // 2 · topic bar
  out.push(`<nav class="kg-nav" aria-label="Topics">
  <div class="site-wrap">
    <ul>
      <li><a href="#start-here">Start here</a></li>
      <li><a href="#latest">Latest</a></li>
${sections.map((s) => `      <li><a href="#${s.id}">${esc(s.title)} <span>${s.articles.length}</span></a></li>`).join('\n')}
    </ul>
  </div>
</nav>`);

  // 3 · the lead story and four features
  out.push(`<section id="featured" class="site-sec kg-front" aria-labelledby="featured-h">
  <div class="site-wrap">
    <h2 id="featured-h">Featured</h2>
    <div class="kg-front-grid">
      <article class="pg-card kg-card kg-tease kg-lead-story">
        ${media(imgLead(P(lead)))}
        <div class="pg-card-body">
          <span class="kg-kicker">${esc(secTitle(lead))}</span>
          ${head(lead)}
          <p>${esc(lead.dek)}</p>
          ${meta(lead)}
        </div>
      </article>
      <div class="kg-features">
${cfg.features.map((s) => bySlug[s]).map((a) => `        <article class="pg-card kg-card kg-tease kg-row">
          ${media(imgFeature(P(a)))}
          <div class="pg-card-body">
            <span class="kg-kicker">${esc(secTitle(a))}</span>
            ${head(a)}
            ${meta(a)}
          </div>
        </article>`).join('\n')}
      </div>
    </div>
  </div>
</section>`);

  // 4 · start here: the pillar (unless it already leads the front) and the five steps in reading order
  const stepRow = (a) => `        <li><article class="pg-card kg-card kg-tease kg-row">
          ${media(imgRow(P(a)))}
          <div class="pg-card-body">
            <span class="kg-kicker">${esc(secTitle(a))}</span>
            ${head(a)}
            ${meta(a)}
          </div>
        </article></li>`;
  const pillarCard = pillarIsLead ? '' : `      <article class="pg-card kg-card kg-tease kg-pillar">
        ${media(imgPillar(P(pillar)))}
        <div class="pg-card-body">
          <span class="kg-kicker">The main guide</span>
          ${head(pillar)}
          <p>${esc(pillar.dek)}</p>
          <span class="link-arrow" aria-hidden="true">Read the guide</span>
        </div>
      </article>
`;
  out.push(`<section id="start-here" class="site-sec site-sec-paper kg-start${pillarIsLead ? ' kg-start-solo' : ''}" aria-labelledby="start-here-h">
  <div class="site-wrap">
    <header class="kg-sec-head">
      <p class="eyebrow">Start here</p>
      <h2 id="start-here-h">Building a kitchen, step by step</h2>
      <p>${pillarIsLead ? 'New to this? Read the main guide above first, then the five that follow it in order.' : 'New to this? Read the main guide first, then the five that follow it in order.'}</p>
    </header>
    <div class="kg-start-grid">
${pillarCard}      <ol class="kg-steps">
${cfg.startHere.map((s) => stepRow(bySlug[s])).join('\n')}
      </ol>
    </div>
  </div>
</section>`);

  // 5 · latest: the newest articles not already shown above (the lead, the features, the pillar and the Start-here steps are)
  const shown = new Set([cfg.lead, ...cfg.features, cfg.pillar, ...cfg.startHere]);
  const latest = arts.filter((a) => !shown.has(a.slug)).sort(ctx.newestFirst).slice(0, LATEST);
  out.push(`<section id="latest" class="site-sec kg-latest" aria-labelledby="latest-h">
  <div class="site-wrap">
    <header class="kg-sec-head"><p class="eyebrow">Latest</p><h2 id="latest-h">Recently published</h2></header>
    <div class="kg-list kg-list-3">
${latest.map((a) => `      <article class="pg-card kg-card kg-tease kg-row">
        ${media(imgRow(P(a)))}
        <div class="pg-card-body">
          <span class="kg-kicker">${esc(secTitle(a))}</span>
          ${head(a)}
          ${meta(a)}
        </div>
      </article>`).join('\n')}
    </div>
  </div>
</section>`);

  // 6 · the topics
  const rowCard = (a) => `      <article class="pg-card kg-card kg-entry kg-row">
        ${media(imgRow(P(a)))}
        <div class="pg-card-body">
          ${head(a)}
          <p>${esc(a.dek)}</p>
          ${meta(a)}
        </div>
      </article>`;
  const photoCard = (a, i) => `      <article class="pg-card kg-card kg-entry">
        ${media(i === 0 ? imgCard(P(a)) : imgCardRow(P(a)))}
        <div class="pg-card-body">
          ${head(a)}
          <p>${esc(a.dek)}</p>
          ${meta(a)}
        </div>
      </article>`;
  for (const s of sections) {
    const list = s.articles;
    const top = list.slice(0, TOP), rows = list.slice(TOP, TOP + ROWS), more = list.slice(TOP + ROWS);
    out.push(`<section id="${s.id}" class="site-sec kg-sec" aria-labelledby="${s.id}-h">
  <div class="site-wrap">
    <header class="kg-sec-head">
      <p class="eyebrow">${list.length} articles</p>
      <h2 id="${s.id}-h">${esc(s.title)}</h2>
      <p>${esc(s.blurb)}</p>
    </header>
    <div class="kg-top">
${top.map(photoCard).join('\n')}
    </div>
${rows.length ? `    <div class="kg-list">
${rows.map(rowCard).join('\n')}
    </div>
` : ''}${more.length ? `    <details class="kg-more">
      <summary>Show the other ${more.length} article${more.length === 1 ? '' : 's'} in ${esc(s.title)}</summary>
      <div class="kg-list">
${more.map(rowCard).join('\n')}
      </div>
    </details>
` : ''}  </div>
</section>`);
  }

  // 7 · colophon
  out.push(`<section class="site-sec kg-colophon" aria-labelledby="colophon-h">
  <div class="site-wrap">
    <h2 id="colophon-h">About this journal</h2>
    <p>The Kitchen Guide is written and published by Barro Kitchens, the team that designs, fabricates and installs stainless-steel kitchens across Luzon. Each article lists its sources under References. Read our <a href="${L.STANDARDS_PATH}">editorial standards</a>, or tell us about an error at <a href="mailto:hello@barroindustries.com">hello@barroindustries.com</a>.</p>
    <p>Photographs are credited on each article. Stock photographs are for illustration only and do not show Barro Kitchens projects unless the caption says so.</p>
    <p class="art-copy art-copy-index">© 2026 Barro Industries OPC. All rights reserved. The text and designs on this page are our own work and may not be copied or reused without written permission. Photographs are credited where they appear.</p>
  </div>
</section>`);

  return { html: out.join('\n\n'), newest, count: arts.length };
}

// the JSON-LD data block of the hub, with the ItemList (registry order), its count and the page's dateModified rewritten
function jsonLd(html, ctx, newest) {
  const m = html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/);
  if (!m) fail('guides/index.html has no JSON-LD block');
  const data = JSON.parse(m[1]);
  const cp = data['@graph'].find((n) => [].concat(n['@type']).includes('CollectionPage'));
  if (!cp) fail('guides/index.html: no CollectionPage in the JSON-LD');
  const list = ctx.arts.map((a, i) => ({ '@type': 'ListItem', position: i + 1, name: a.h1, url: BASE + href(a) }));
  cp.mainEntity = { '@type': 'ItemList', numberOfItems: list.length, itemListElement: list };
  const next = {};
  for (const [k, v] of Object.entries(cp)) { next[k] = v; if (k === 'inLanguage') next.dateModified = `${newest}T08:00:00+08:00`; }
  if (!next.dateModified) next.dateModified = `${newest}T08:00:00+08:00`;
  Object.keys(cp).forEach((k) => delete cp[k]);
  Object.assign(cp, next);
  return html.replace(m[0], `<script type="application/ld+json">\n${JSON.stringify(data, null, 2)}\n</script>`);
}

function build(html, ctx) {
  const s = html.indexOf(START), e = html.indexOf(END);
  if (s < 0 || e < 0 || e < s || html.indexOf(START, s + 1) >= 0) fail(`guides/index.html must carry the KG-HUB:START and KG-HUB:END markers exactly once each, directly inside <main>`);
  const r = render(ctx);
  let next = html.slice(0, s) + START + '\n' + r.html + '\n' + END + html.slice(e + END.length);
  next = jsonLd(next, ctx, r.newest);
  return next;
}

function main() {
  const check = process.argv.includes('--check');
  let ctx, html, next;
  try {
    ctx = load();
    html = fs.readFileSync(HUB, 'utf8');
    next = build(html, ctx);
  } catch (err) {
    if (!(err instanceof L.GuidesError)) throw err;
    console.error('FAIL: ' + err.message);
    process.exit(1);
  }
  if (next === html) { console.log(check ? 'PASS: guides/index.html is current (' + ctx.arts.length + ' articles, ' + ctx.sections.length + ' topics)' : 'guides/index.html is already up to date'); return; }
  if (check) {
    console.error('FAIL: guides/index.html is stale — its generated part does not match scripts/guides-hub.json, the photo manifests and the articles. FIX: node scripts/build-guides-hub.js   (run node scripts/apply-guide-template.js first when an article changed)');
    process.exit(1);
  }
  fs.writeFileSync(HUB, next);
  console.log(`guides/index.html rewritten: ${ctx.arts.length} articles, ${ctx.sections.length} topics`);
}

if (require.main === module) main();
module.exports = { load, render, build, START, END };
