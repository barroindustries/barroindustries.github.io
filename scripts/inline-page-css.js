#!/usr/bin/env node
/**
 * inline-page-css.js — keeps the stylesheet of the standalone public content pages INLINE in their <head>, together with the
 * Content-Security-Policy hash that lets the browser run it. Every static page of the public site opts in except the homepage (its own
 * block, scripts/inline-site-css.js) and /catalogue/: the product pages, /services/ and its service pages, /work/ and its project pages,
 * /areas-we-serve/, /faq/ and the guides. tests/page-first-paint.test.mjs finds them on disk and in sitemap.xml and fails for a page that has no block.
 *
 *   node scripts/inline-page-css.js            rewrite every opted-in page from the css files named in its marker
 *   node scripts/inline-page-css.js --check    exit 1 when a block or a CSP hash is stale or wrong (CHECK 9 runs this)
 *
 * AFTER EDITING css/pages.css OR css/guides.css (or css/site.css), RUN THIS SCRIPT. It rewrites every page whose marker names the file you edited:
 * css/pages.css and css/site.css are in all of them, css/guides.css only in the three /guides/ pages. After css/site.css run scripts/inline-site-css.js
 * as well (the homepage's copy). The pre-commit hook runs neither script; CHECK 9 (--check here) and CHECK 11, and the tests, fail while a copy is stale.
 *
 * WHY. Same reason as scripts/inline-site-css.js (the homepage): a stylesheet <link> blocks the first paint, and on a phone behind a real
 * network that is a round trip (plus the server's own response time) per stylesheet between the HTML and the first thing a visitor sees.
 * Measured with Lighthouse 12 mobile on the calibrated stand-in for the live host (HTTP/2, 250 ms server response), a /products/ page that
 * links css/site.css + css/pages.css and the Google Fonts scored 82-86 (first paint 3.2-3.8 s); with the SAME css bytes inline it scored 97-98
 * when the paint won the race against the font files and 78-90 when it lost; with the fonts also requested after the page has loaded
 * (js/late-fonts.js, plus a <noscript> link) it scored 100 every time (first paint 1.24 s). The stylesheets stay the one place the rules
 * are written and edited; this script copies them, verbatim and in the order the marker lists them, between two marker comments, so a copy
 * can never be edited by hand without CI saying so. No minifier on purpose: what is inline is exactly what the tests read.
 *
 * HOW A PAGE OPTS IN. Put this where the <link rel="stylesheet" href="/css/…"> lines used to be, and run the script; then move the Google Fonts
 * <link> into a <noscript> and add <script defer src="/js/late-fonts.js"></script> after /js/site.js (the fonts are what a first paint races):
 *
 *   <!-- PAGE-CSS:START css/site.css css/pages.css — generated by scripts/inline-page-css.js — DO NOT HAND-EDIT: edit the css files, then run node scripts/inline-page-css.js -->
 *   <!-- PAGE-CSS:END -->
 *
 * The files after START are the sources, in order (css/ only): "css/site.css css/pages.css" for a content or product page, and
 * "css/site.css css/pages.css css/guides.css" for a guide (the order the <link> lines had; a later file overrides an earlier one). The script writes
 * <style id="page-css">…</style> between the markers and puts the sha256 of that element's text into the page's CSP, in style-src (the pages have
 * no 'unsafe-inline': the hash is what lets the one block run). Every page that opts in must also have its fonts in a <noscript> link and load
 * js/late-fonts.js, and must keep every <link rel="stylesheet"> out of its head: tests/page-first-paint.test.mjs and CHECK 9 pin all of that.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const START_PREFIX = '<!-- PAGE-CSS:START ';
const START_SUFFIX = ' — generated by scripts/inline-page-css.js — DO NOT HAND-EDIT: edit the css files, then run node scripts/inline-page-css.js -->';
const END = '<!-- PAGE-CSS:END -->';
const CSP_RE = /(<meta http-equiv="Content-Security-Policy" content=")([^"]*)(">)/;
// never walked: not public pages (or not pages at all)
const SKIP = new Set(['.git', '.github', '.githooks', '.claude', '.vscode', 'node_modules', 'functions', 'private', 'archive', 'downloads', 'site', 'icons', 'js', 'css', 'data', 'docs', 'specs', 'tests', 'scripts', 'fable-workplan']);

class InlinePageCssError extends Error {}

// The sources named in a page's START marker, e.g. ['css/site.css', 'css/pages.css'] — or null when the page has no marker.
function sourcesOf(html) {
  const s = html.indexOf(START_PREFIX);
  if (s < 0) return null;
  if (html.indexOf(START_PREFIX, s + 1) >= 0) throw new InlinePageCssError('the page has more than one PAGE-CSS:START marker');
  const e = html.indexOf(START_SUFFIX, s);
  if (e < 0) throw new InlinePageCssError('the PAGE-CSS:START marker is not the generated one (it must read "<!-- PAGE-CSS:START css/… — generated by scripts/inline-page-css.js — DO NOT HAND-EDIT: … -->")');
  const files = html.slice(s + START_PREFIX.length, e).trim().split(/\s+/).filter(Boolean);
  if (!files.length) throw new InlinePageCssError('the PAGE-CSS:START marker lists no stylesheet');
  for (const f of files) if (!/^css\/[a-z0-9][a-z0-9._-]*\.css$/.test(f)) throw new InlinePageCssError('the PAGE-CSS:START marker lists "' + f + '", which is not a file in css/');
  if (new Set(files).size !== files.length) throw new InlinePageCssError('the PAGE-CSS:START marker lists a stylesheet twice');
  return files;
}

// The text of the <style> element and its CSP hash, from the sources (read(file) → text).
function styleOf(files, read) {
  const css = files.map((f) => read(f).replace(/\s+$/, '')).join('\n');
  if (/<\/style/i.test(css)) throw new InlinePageCssError('a stylesheet contains "</style", which would end the inline block early');
  const text = '\n' + css + '\n';
  return { css, text, hash: 'sha256-' + crypto.createHash('sha256').update(text, 'utf8').digest('base64') };
}

function blockOf(files, style) {
  return START_PREFIX + files.join(' ') + START_SUFFIX + '\n<style id="page-css">' + style.text + '</style>\n' + END;
}

// Returns the style-src directive of a CSP value as an array of tokens, or null.
function styleSrc(csp) {
  const d = csp.split(';').map((x) => x.trim()).find((x) => /^style-src\s/.test(x));
  return d ? d.split(/\s+/).slice(1) : null;
}

// The page with its block rewritten from the sources and its CSP's style-src carrying exactly the block's hash. Throws when the page is not set up.
function build(html, read) {
  const files = sourcesOf(html);
  if (!files) throw new InlinePageCssError('the page has no PAGE-CSS block');
  const s = html.indexOf(START_PREFIX), e = html.indexOf(END, s);
  if (e < 0) throw new InlinePageCssError('PAGE-CSS:START has no PAGE-CSS:END after it');
  if (html.indexOf(END, e + 1) >= 0) throw new InlinePageCssError('the page has more than one PAGE-CSS:END marker');
  const style = styleOf(files, read);
  let out = html.slice(0, s) + blockOf(files, style) + html.slice(e + END.length);
  const m = out.match(CSP_RE);
  if (!m) throw new InlinePageCssError('the page has no <meta http-equiv="Content-Security-Policy" content="…">');
  const tokens = styleSrc(m[2]);
  if (!tokens) throw new InlinePageCssError('the page\'s CSP has no style-src directive');
  if (tokens.includes("'unsafe-inline'")) throw new InlinePageCssError("the page's CSP allows 'unsafe-inline' styles — the hash is what lets the one inline block run");
  const next = tokens.filter((t) => !/^'sha256-/.test(t));
  next.splice(next.includes("'self'") ? next.indexOf("'self'") + 1 : 0, 0, "'" + style.hash + "'");
  const csp = m[2].split(';').map((x) => (/^\s*style-src\s/.test(x) ? ' style-src ' + next.join(' ') : x)).join(';').replace(/^ /, '');
  return out.replace(CSP_RE, (_, a, __, c) => a + csp + c);
}

// The opted-in pages under root: [{file (relative, forward slashes), html}] in path order.
function findPages(root = ROOT) {
  const found = [];
  (function walk(dir, depth) {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
      if (ent.isDirectory()) { if (depth < 5 && !SKIP.has(ent.name) && !ent.name.startsWith('.')) walk(path.join(dir, ent.name), depth + 1); }
      else if (ent.name === 'index.html' && dir !== root) {
        const html = fs.readFileSync(path.join(dir, ent.name), 'utf8');
        if (html.includes('PAGE-CSS:START')) found.push({ file: path.relative(root, path.join(dir, ent.name)).split(path.sep).join('/'), html });
      }
    }
  })(root, 0);
  return found.sort((a, b) => (a.file < b.file ? -1 : 1));
}

function main() {
  const check = process.argv.includes('--check');
  const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');
  const pages = findPages(ROOT);
  if (!pages.length) { console.error('FAIL: no page carries a PAGE-CSS block.'); process.exit(1); }
  let bad = 0, stale = 0, written = 0;
  for (const { file, html } of pages) {
    let next;
    try { next = build(html, read); } catch (err) {
      if (!(err instanceof InlinePageCssError)) throw err;
      console.error('FAIL: ' + file + ': ' + err.message);
      bad++; continue;
    }
    if (next === html) continue;
    if (check) {
      const files = sourcesOf(html);
      console.error('FAIL: ' + file + ': the inline <style id="page-css"> block or the CSP hash is stale — the block must equal ' + files.join(' + ') + ' and style-src must carry its sha256.');
      bad++; stale++;
    } else { fs.writeFileSync(path.join(ROOT, file), next); written++; }
  }
  if (stale) console.error('  FIX: node scripts/inline-page-css.js   (it rewrites all ' + stale + ' stale page(s); after css/site.css also run node scripts/inline-site-css.js; do not edit a block by hand)');
  if (bad) process.exit(1);
  if (check) console.log('PASS: the inline stylesheet and the CSP hash of the ' + pages.length + ' opted-in page(s) are current (' + pages.map((p) => p.file.replace(/\/index\.html$/, '/')).join(', ') + ')');
  else console.log(written ? 'inlined the stylesheets into ' + written + ' of ' + pages.length + ' page(s)' : 'all ' + pages.length + ' page(s) are already up to date');
}

if (require.main === module) main();
module.exports = { START_PREFIX, START_SUFFIX, END, sourcesOf, styleOf, blockOf, styleSrc, build, findPages, InlinePageCssError };
